assert(version.includes("APP_VERSION = '1.19.5'"));
assert(useCase.includes('ConfirmarImportacaoHistoricaFinanceiraUseCase'));
assert(useCase.includes('faturamentoTotal'));
assert(useCase.includes('custoTotal'));
assert(useCase.includes('lucroTotal'));
