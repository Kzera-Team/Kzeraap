assert(view.includes('Ver valores financeiros') && view.includes('Faturamento') && view.includes('Custo') && view.includes('Lucro')); // valores ficam em detalhe avançado
assert(view.includes('Estoque não foi alterado') || view.includes('Estoque não será mexido')); 
assert(app.includes('new ConfirmarImportacaoHistoricaFinanceiraUseCase'));
